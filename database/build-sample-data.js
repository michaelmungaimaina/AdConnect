'use strict';
/**
 * Builds database/sample-data.sql  ->  node database/build-sample-data.js
 * Demo content: service catalogue, welcome e-mail + 50 follow-ups, 14 blog posts, 40 subscribers
 * (with send position + e-mail log), a few bookings and proposals. All people/e-mails are fictional
 * (example.com/.org/.net). Every INSERT is IGNORE, so re-running never duplicates rows.
 */
const fs = require('fs');
const path = require('path');
const catalogue = require('./seed/catalogue');
const steps = require('./seed/emails');
const blogs = require('./seed/blogs');
const subs = require('./seed/subscribers');

const q = (v) => (v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'");
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const id = (p, n) => (p + String(n).padStart(4, '0')).slice(0, 20);
const out = ['-- AdConnect sample data (generated by build-sample-data.js). Run AFTER schema.sql.', 'SET NAMES utf8mb4;', 'SET FOREIGN_KEY_CHECKS=0;', ''];
const now = 'NOW()';

// catalogue
let ci = 0;
for (const c of catalogue) {
  ci++;
  out.push(`INSERT IGNORE INTO service_categories (id,slug,name,tagline,description,icon,sort_order,status,allow_booking,allow_proposal,session_minutes,host_key,host_name,created_at,updated_at) VALUES (${q(id('smp-cat', ci))},${q(c.slug)},${q(c.name)},${q(c.tagline)},${q(c.description)},${q(c.icon)},${ci},'ACTIVE',1,1,${c.session_minutes},${q(c.host_key)},${q(c.host_name)},${now},${now});`);
  let si = 0;
  for (const s of c.services) {
    si++;
    out.push(`INSERT IGNORE INTO services (id,category_id,slug,name,summary,description,features,icon,starting_price,delivery_time,sort_order,featured,status,created_at,updated_at) SELECT ${q(id('smp-svc', ci * 100 + si))}, id, ${q(s.slug)},${q(s.name)},${q(s.summary)},${q(s.description || s.summary)},${q(JSON.stringify(s.features || []))},${q(s.icon || 'fa-check')},'','',${si},${si <= 2 ? 1 : 0},'ACTIVE',${now},${now} FROM service_categories WHERE slug=${q(c.slug)};`);
  }
}
out.push('');
// campaign
for (const e of steps) {
  out.push(`INSERT IGNORE INTO email_campaign_steps (id,step,day_offset,category,subject,preheader,kicker,title,body_html,cta_text,cta_url,status,created_at,updated_at) VALUES (${q(id('smp-step', e.step))},${e.step},${e.day},${q(e.category)},${q(e.subject)},${q(e.preheader || '')},${q(e.kicker || '')},${q(e.title)},${q(e.body_html)},${q(e.cta_text || '')},${q(e.cta_url || '')},'ACTIVE',${now},${now});`);
}
out.push('');
// blogs
blogs.forEach((b, i) => {
  out.push(`INSERT IGNORE INTO blog_posts (id,title,slug,category,status,excerpt,content,author,cover_image,view_count,created_at,updated_at) VALUES (${q(id('smp-blog', i + 1))},${q(b.title)},${q(b.slug || slug(b.title))},${q(b.category)},'PUBLISHED',${q(b.excerpt)},${q(b.content)},${q(b.author)},NULL,${20 + ((i * 37) % 180)},NOW() - INTERVAL ${b.days_ago || i * 5 + 2} DAY,NOW());`);
});
out.push('');
// subscribers + send position + log
const stepsBy = Object.fromEntries(steps.map((s) => [s.step, s]));
subs.forEach((s, i) => {
  const n = i + 1, sid = id('smp-sub', n), d = s.days_ago_subscribed;
  const active = s.status === 'SUBSCRIBED';
  const sent = s.status === 'PENDING' ? -1 : Math.min(50, Math.floor(d / 3));   // last step sent
  const sentAny = sent >= 0;
  const next = active && sent < 50 ? `NOW() + INTERVAL ${((i * 7) % 72) + 1} HOUR` : 'NULL';
  const unsub = s.status === 'UNSUBSCRIBED' ? `NOW() - INTERVAL ${Math.max(1, d - 10)} DAY` : 'NULL';
  const reason = s.status === 'UNSUBSCRIBED' ? q(['Too many emails', 'Not relevant', 'No longer interested', 'Other'][i % 4]) : 'NULL';
  out.push(`INSERT IGNORE INTO subscribers (id,email,name,phone,interests,status,source,current_step,next_send_at,last_sent_at,subscribed_at,unsubscribed_at,unsubscribe_reason,notes,created_at,updated_at) VALUES (${q(sid)},${q(s.email)},${q(s.name)},${q(s.phone)},${q(JSON.stringify(s.interests))},${q(s.status)},${q(s.source)},${sentAny ? sent : -1},${next},${sentAny ? `NOW() - INTERVAL ${Math.max(0, d - sent * 3)} DAY` : 'NULL'},NOW() - INTERVAL ${d} DAY,${unsub},${reason},'Sample subscriber',NOW() - INTERVAL ${d} DAY,NOW());`);
  if (sentAny) {
    for (let st = 0; st <= sent; st++) {
      const bounced = s.status === 'BOUNCED' && st === sent;
      out.push(`INSERT IGNORE INTO email_log (id,email,kind,step,broadcast_id,subject,status,error,created_at) VALUES (${q(id('smp-log', n * 100 + st))},${q(s.email)},'CAMPAIGN',${st},NULL,${q(stepsBy[st].subject)},${bounced ? "'FAILED'" : "'SENT'"},${bounced ? q('550 mailbox unavailable') : 'NULL'},NOW() - INTERVAL ${Math.max(0, d - st * 3)} DAY);`);
    }
  }
});
out.push('');
// broadcast
out.push(`INSERT IGNORE INTO broadcasts (id,subject,preheader,title,body_html,cta_text,cta_url,audience,status,recipients,sent_count,failed_count,created_by,sent_at,created_at,updated_at) VALUES ('smp-bc0001','New: book a free 30-minute session online','Pick a service, pick a time.','Book a session with AdConnect','<p>Hi {{firstName}},</p><p>You can now book a session for any of our services straight from the website. Choose a category, pick a time, and we will confirm by email.</p>','Book a session','/book.html','ALL','SENT',30,29,1,'Sample',NOW() - INTERVAL 14 DAY,NOW() - INTERVAL 15 DAY,NOW());`);
out.push('');
// bookings (future + past)
const bk = [
  ['digital-marketing', 'Digital Marketing', 'Wanjiru Kamau', 'wanjiru.k@example.com', 'ONLINE', 3, '10:00', '10:30', 'misgina', 'Misgina Fitwi', 'Plan ads for a new boutique launch', 'CONFIRMED'],
  ['web-development', 'Web Development', 'Brian Otieno', 'brian.otieno@example.org', 'ONLINE', 4, '14:00', '14:45', 'michael', 'Michael Maina', 'Online shop with M-Pesa checkout', 'PENDING'],
  ['database-management', 'Database Management', 'Amina Hassan', 'amina.hassan@example.net', 'ONLINE', 6, '09:00', '09:45', 'michael', 'Michael Maina', 'Migrate spreadsheets to MySQL', 'CONFIRMED'],
  ['data-analytics', 'Data Analytics', 'Peter Mwangi', 'peter.mwangi@example.com', 'ONLINE', 7, '11:00', '11:45', 'michael', 'Michael Maina', 'Survey analysis for an NGO', 'PENDING'],
  ['consulting', 'Consulting', 'Grace Achieng', 'grace.achieng@example.org', 'IN_PERSON', -2, '15:00', '15:45', 'team', 'AdConnect Team', 'Technology roadmap review', 'COMPLETED'],
  ['software-development', 'Software Development', 'Daniel Kiprop', 'daniel.kiprop@example.net', 'ONLINE', -5, '10:00', '10:45', 'michael', 'Michael Maina', 'Inventory system scoping', 'COMPLETED'],
  ['software-design', 'Software Design', 'Fatuma Ali', 'fatuma.ali@example.com', 'ONLINE', -1, '16:00', '16:45', 'michael', 'Michael Maina', 'Mobile app UX review', 'CANCELLED'],
];
bk.forEach((b, i) => {
  const ref = 'BK-SAMPL' + (i + 1);
  out.push(`INSERT IGNORE INTO bookings (id,reference,category_id,category_slug,category_name,name,email,phone,company,session_mode,booking_date,start_time,end_time,host_key,host_name,topic,status,meeting_link,location,slot_key,created_at,updated_at) SELECT ${q(id('smp-bk', i + 1))},${q(ref)},id,${q(b[0])},${q(b[1])},${q(b[2])},${q(b[3])},'',NULL,${q(b[4])},CURDATE() + INTERVAL ${b[5]} DAY,${q(b[6])},${q(b[7])},${q(b[8])},${q(b[9])},${q(b[10])},${q(b[11])},'',${q(b[4] === 'IN_PERSON' ? 'Nairobi' : '')},${q(`smp-${b[8]}-${i}-${b[6]}`)},NOW() - INTERVAL 2 DAY,NOW() FROM service_categories WHERE slug=${q(b[0])};`);
});
out.push('');
// proposals
const pr = [
  ['web-development', 'Web Development', 'Hassan Omar', 'hassan.omar@example.com', 'School fees portal', 'Parents view balances and pay via M-Pesa.', 'KES 300k–600k', '3 months', 'UNDER_REVIEW', ''],
  ['data-analytics', 'Data Analytics', 'Mercy Chebet', 'mercy.chebet@example.org', 'Household survey analysis', '1,200 survey responses to clean, analyse and report.', 'KES 50k–100k', '6 weeks', 'QUOTED', 'KES 85,000'],
  ['digital-marketing', 'Digital Marketing', 'Kevin Maina', 'kevin.maina@example.net', 'Clinic lead generation', 'Run Facebook and Google ads for a new clinic.', 'KES 30k–60k / month', 'Ongoing', 'NEW', ''],
  ['database-management', 'Database Management', 'Joyce Atieno', 'joyce.atieno@example.com', 'Customer database clean-up', 'Deduplicate and restructure 40k customer records.', 'KES 40k–80k', '4 weeks', 'ACCEPTED', 'KES 60,000'],
  ['software-development', 'Software Development', 'Ibrahim Yusuf', 'ibrahim.yusuf@example.org', 'Fleet tracking dashboard', 'Dashboard from GPS data feed.', 'KES 500k+', '4 months', 'NEEDS_INFO', ''],
];
pr.forEach((p, i) => {
  out.push(`INSERT IGNORE INTO proposals (id,reference,category_id,category_slug,category_name,name,email,phone,company,title,summary,budget_range,timeline,status,quote_amount,admin_notes,created_at,updated_at) SELECT ${q(id('smp-pr', i + 1))},${q('PR-SAMPL' + (i + 1))},id,${q(p[0])},${q(p[1])},${q(p[2])},${q(p[3])},'',NULL,${q(p[4])},${q(p[5])},${q(p[6])},${q(p[7])},${q(p[8])},${q(p[9])},'Sample proposal',NOW() - INTERVAL ${i + 1} DAY,NOW() FROM service_categories WHERE slug=${q(p[0])};`);
});
out.push('', 'SET FOREIGN_KEY_CHECKS=1;', '');
fs.writeFileSync(path.join(__dirname, 'sample-data.sql'), out.join('\n'));
console.log('wrote sample-data.sql', out.length, 'lines');
